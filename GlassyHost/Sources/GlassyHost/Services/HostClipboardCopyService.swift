import AppKit
import Foundation

/// Decides what a clipboard change means from its types alone, which macOS lets
/// an app inspect without showing a paste alert.
enum HostClipboardCopyPolicy {
    /// Added to text written by `HostClipboardPasteService`.
    static let fromDeviceType = NSPasteboard.PasteboardType("dev.bunn.glassydesk.from-device")

    /// Markers from https://nspasteboard.org that password managers and other
    /// apps use to say that an item should not leave the clipboard.
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "com.typeit4me.clipping",
        "net.antelle.keeweb"
    ]
    private static let textTypes: Set<String> = [
        NSPasteboard.PasteboardType.string.rawValue, "public.text", "public.url"
    ]
    private static let fileTypes: Set<String> = [
        NSPasteboard.PasteboardType.fileURL.rawValue, "NSFilenamesPboardType"
    ]

    enum Contents: Equatable {
        case fromDevice, concealed, files, text, unsupported, empty
    }

    static func contents(ofTypes types: [String]) -> Contents {
        let types = Set(types)
        guard !types.isEmpty else { return .empty }
        if types.contains(fromDeviceType.rawValue) { return .fromDevice }
        if !types.isDisjoint(with: privateTypes) { return .concealed }
        // A copied file also offers its name as text; the file is what was meant.
        if !types.isDisjoint(with: fileTypes) { return .files }
        return types.isDisjoint(with: textTypes) ? .unsupported : .text
    }
}

/// Sends the controlling device what it copies on this Mac.
///
/// While a device follows the clipboard, this watches only the change count and,
/// when it moves, the item's types. It reads the text only if that device's own
/// input came just before the change, so copies made by someone at the Mac, by a
/// background app, or by Universal Clipboard stay here. Reading happens on this
/// service's queue because macOS may hold the read while it shows a paste alert.
final class HostClipboardCopyService: @unchecked Sendable {
    static let allowsCopyKey = "clipboard.allowsCopyToDevices"
    /// Long enough for a menu or an app to finish copying after a click or key.
    static let recentInputWindow: TimeInterval = 5

    struct Pasteboard: Sendable {
        var changeCount: @Sendable () -> Int = { NSPasteboard.general.changeCount }
        var types: @Sendable () -> [String] = {
            (NSPasteboard.general.types ?? []).map(\.rawValue)
        }
        var readText: @Sendable () -> String? = { NSPasteboard.general.string(forType: .string) }
        /// The person turned off Paste from Other Apps for Glassy Desk.
        var isDenied: @Sendable () -> Bool = {
            if #available(macOS 15.4, *) {
                return NSPasteboard.general.accessBehavior == .alwaysDeny
            }
            return false
        }
    }

    private let queue = DispatchQueue(label: "dev.bunn.glassydesk.host.clipboard-copy", qos: .utility)
    private let send: @Sendable (HostProtocol.ClipboardCopy, UUID) -> Void
    private let pasteboard: Pasteboard
    private let defaults: UserDefaults
    private let now: @Sendable () -> TimeInterval
    private let pollInterval: DispatchTimeInterval?

    private let inputLock = NSLock()
    private var lastInputTime: TimeInterval?

    // Isolated to `queue`.
    private var followers: Set<UUID> = []
    private var toldDenied: Set<UUID> = []
    private var lastChangeCount = 0
    private var timer: DispatchSourceTimer?

    init(send: @escaping @Sendable (HostProtocol.ClipboardCopy, UUID) -> Void,
         pasteboard: Pasteboard = Pasteboard(),
         defaults: UserDefaults = .standard,
         now: @escaping @Sendable () -> TimeInterval = { ProcessInfo.processInfo.systemUptime },
         pollInterval: DispatchTimeInterval? = .milliseconds(250)) {
        self.send = send
        self.pasteboard = pasteboard
        self.defaults = defaults
        self.now = now
        self.pollInterval = pollInterval
    }

    var allowsCopy: Bool {
        get { defaults.object(forKey: Self.allowsCopyKey) as? Bool ?? true }
        set { defaults.set(newValue, forKey: Self.allowsCopyKey) }
    }

    /// Called for every event from the device that controls this Mac.
    func noteRemoteInput() {
        let time = now()
        inputLock.withLock { lastInputTime = time }
    }

    func handle(_ request: HostProtocol.ClipboardCopyRequest, from client: UUID, isInputOwner: Bool) {
        queue.async { [self] in
            switch request {
            case .follow:
                // Starts from the current clipboard, so nothing already on it moves.
                if followers.isEmpty { lastChangeCount = pasteboard.changeCount() }
                followers.insert(client)
                updateTimer()
            case .stopFollowing:
                followers.remove(client)
                toldDenied.remove(client)
                updateTimer()
            case .sendNow:
                send(requestedCopy(isInputOwner: isInputOwner), client)
            }
        }
    }

    func clientEnded(_ client: UUID) {
        queue.async { [self] in
            followers.remove(client)
            toldDenied.remove(client)
            updateTimer()
        }
    }

    /// Runs a pending change check and waits for it, for tests.
    func checkForChangesAndWait() {
        queue.sync { checkForChange() }
    }

    private func updateTimer() {
        guard let pollInterval else { return }
        if followers.isEmpty {
            timer?.cancel()
            timer = nil
        } else if timer == nil {
            let timer = DispatchSource.makeTimerSource(queue: queue)
            timer.schedule(deadline: .now() + pollInterval, repeating: pollInterval, leeway: .milliseconds(100))
            timer.setEventHandler { [weak self] in self?.checkForChange() }
            timer.resume()
            self.timer = timer
        }
    }

    private func checkForChange() {
        let changeCount = pasteboard.changeCount()
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        guard allowsCopy, !followers.isEmpty, hasRecentInput else { return }

        let outcome: HostProtocol.ClipboardCopy
        switch HostClipboardCopyPolicy.contents(ofTypes: pasteboard.types()) {
        case .files:
            outcome = .init(outcome: .files, isAutomatic: true)
        case .text:
            guard !pasteboard.isDenied() else {
                // Explain once per device; every later copy would say the same.
                for client in followers.subtracting(toldDenied) {
                    send(.init(outcome: .blockedByMac, isAutomatic: true), client)
                }
                toldDenied.formUnion(followers)
                return
            }
            outcome = textCopy(isAutomatic: true)
        case .fromDevice, .concealed, .unsupported, .empty:
            return
        }
        guard outcome.outcome != .empty else { return }
        for client in followers { send(outcome, client) }
    }

    private var hasRecentInput: Bool {
        let time = now()
        return inputLock.withLock {
            lastInputTime.map { time - $0 <= Self.recentInputWindow } ?? false
        }
    }

    /// Someone asked, so say what happened even when nothing can be sent.
    private func requestedCopy(isInputOwner: Bool) -> HostProtocol.ClipboardCopy {
        guard allowsCopy, isInputOwner else { return .init(outcome: .notAllowed, isAutomatic: false) }
        switch HostClipboardCopyPolicy.contents(ofTypes: pasteboard.types()) {
        case .empty: return .init(outcome: .empty, isAutomatic: false)
        case .concealed: return .init(outcome: .concealed, isAutomatic: false)
        case .files: return .init(outcome: .files, isAutomatic: false)
        case .unsupported: return .init(outcome: .unsupported, isAutomatic: false)
        case .fromDevice, .text:
            guard !pasteboard.isDenied() else { return .init(outcome: .blockedByMac, isAutomatic: false) }
            return textCopy(isAutomatic: false)
        }
    }

    private func textCopy(isAutomatic: Bool) -> HostProtocol.ClipboardCopy {
        guard let text = pasteboard.readText(), !text.isEmpty else {
            return .init(outcome: .empty, isAutomatic: isAutomatic)
        }
        guard text.utf8.count <= HostProtocol.maximumClipboardTextLength else {
            return .init(outcome: .tooLarge, isAutomatic: isAutomatic)
        }
        return .init(outcome: .text, isAutomatic: isAutomatic, text: text)
    }
}
